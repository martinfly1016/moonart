(function () {
  const catalog = window.MojiMoonHeartCatalog;
  const data = window.MojiMoonToolData;
  if (!catalog || !data || !Array.isArray(data.items)) return;
  const seen = new Set(data.items.map((item) => item.value));
  for (const group of catalog.groups) {
    for (const item of group.items) {
      if (seen.has(item.value)) continue;
      seen.add(item.value);
      const tags = new Set([...(item.tags || []), 'ハート', '絵文字 コピペ', '絵文字コピペ', 'line']);
      data.items.push({
        value: item.value,
        label: item.label,
        category: 'heart',
        tags: [...tags]
      });
    }
  }
  if (typeof document !== 'undefined' && document.body && document.body.dataset.defaultCategory === 'heart') {
    data.pageSize = 120;
  }
})();
